// Regenerate the emoji tables in src/core/vendor from gemoji (GitHub's emoji
// names, MIT): every name and alias maps to its glyph, and each tag and
// description word maps to the emoji it describes, for :name: completion.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gemoji } from "gemoji";

const root = fileURLToPath(new URL("../", import.meta.url));
const { version } = JSON.parse(fs.readFileSync(path.join(root, "node_modules/gemoji/package.json"), "utf8"));
const stopWords = new Set(["and", "the", "with", "for", "from", "off", "out", "its"]);
const data = {}, search = {};
for (const entry of gemoji) {
  for (const name of entry.names) data[name] = entry.emoji;
  const words = [...entry.tags, ...entry.description.toLowerCase().split(/[^a-z0-9]+/)];
  for (const word of new Set(words.map((word) => word.toLowerCase()))) {
    if (word.length < 3 || stopWords.has(word)) continue;
    (search[word] ||= []).push(entry.names[0]);
  }
}
const header = (what) => `// ${what}, generated by scripts/make-emoji.mjs from gemoji ${version}\n// (MIT, https://github.com/wooorm/gemoji). Do not edit by hand.\n`;
fs.writeFileSync(path.join(root, "src/core/vendor/emoji-data.js"), header("Emoji name → glyph") + `export const EMOJI_DATA = ${JSON.stringify(data)};\n`);
fs.writeFileSync(path.join(root, "src/core/vendor/emoji-search.js"), header("Emoji keyword → names") + `export const EMOJI_SEARCH = ${JSON.stringify(search)};\n`);
console.log(`Wrote ${Object.keys(data).length} names and ${Object.keys(search).length} keywords`);
